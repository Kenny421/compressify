# frozen_string_literal: true

module Compressify
  class Config
    attr_accessor :queue_name, :enabled, :purge_original, :max_download_bytes,
                  :default_image_options, :default_video_options, :dedupe_enabled, :metadata_key,
                  :skip_if_already_compressed, :image_queue_name, :video_queue_name,
                  :job_lock_ttl, :image_max_concurrency, :video_max_concurrency,
                  :concurrency_retry_delay, :image_min_bytes_for_compression,
                  :adaptive_quality_enabled, :adaptive_quality_min,
                  :adaptive_quality_large_image_pixels, :adaptive_quality_large_file_bytes,
                  :reuse_existing_derivatives, :tempfile_dir,
                  :skip_if_no_resize_needed, :skip_larger_output, :postgres_fingerprint_lookup

    def initialize
      # Master switch for background processing.
      @enabled = true

      # Default ActiveJob queue for processing work.
      @queue_name = :default
      # Optional media-specific queues. Falls back to queue_name when nil.
      @image_queue_name = :compressify_images
      @video_queue_name = :compressify_videos

      # TTL for cache-backed idempotency locks.
      @job_lock_ttl = 10.minutes

      # Optional in-flight caps per media type. Nil disables the cap.
      @image_max_concurrency = 8
      @video_max_concurrency = 2

      # Delay used when re-enqueuing after hitting a concurrency cap.
      @concurrency_retry_delay = 5.seconds

      # Purge replaced blobs after swap when they are no longer attached.
      @purge_original = true
      # Avoid replacing a smaller source with a larger compressed file.
      @skip_larger_output = true

      # Safety cap for blob downloads in the job.
      @max_download_bytes = 100.megabytes
      # Skip tiny images where recompression rarely saves much.
      @image_min_bytes_for_compression = 50.kilobytes

      # Skip recompressing when the same output already exists for the same options.
      @dedupe_enabled = true

      # Skip blobs that were already generated by Compressify for the same target/options.
      @skip_if_already_compressed = true

      # Reattach an existing derivative for the same source+options when available.
      @reuse_existing_derivatives = true
      # Opt in after installing the documented PostgreSQL expression index.
      @postgres_fingerprint_lookup = false

      # Optional fast local tmp directory for processing tempfiles.
      @tempfile_dir = ENV["COMPRESSIFY_TMPDIR"].presence

      # Skip processing when an image already fits within resize_to_limit bounds.
      @skip_if_no_resize_needed = false

      # Reduce quality automatically for very large images/files.
      @adaptive_quality_enabled = true
      @adaptive_quality_min = 60
      @adaptive_quality_large_image_pixels = 4_000_000 # ~4MP
      @adaptive_quality_large_file_bytes = 3.megabytes

      # Metadata key used on ActiveStorage::Blob.
      @metadata_key = "compressify"

      @default_image_options = {
        # :jpg, :png, :webp, :avif (nil keeps original)
        format: nil,
        # jpg/webp/avif quality. Encoder interpretation may vary by format.
        quality: 80,
        # [w, h] - downscale only
        resize_to_limit: nil,
        # [w, h] - exact output dimensions (center-crop to fit)
        resize_to_fill: nil,
        # Remove metadata such as EXIF.
        strip: true,
        # Passed directly to the vips saver.
        saver: {}
      }

      @default_video_options = {
        # Video processing requires ffmpeg + streamio-ffmpeg.
        enabled: false,
        format: "mp4",
        video_codec: "libx264",
        audio_codec: "aac",
        crf: 28,
        preset: "medium",
        max_width: nil,
        max_height: nil,
        extra_args: []
      }
    end
  end
end
